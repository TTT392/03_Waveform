//JustFloat协议
void Send_VOFA_Float(float data){
  uint8_t tx_buf[8];//准备八个字节，拆浮点数
  uint8_t *p =(uint8_t*)&data;
  tx_buf[0] = p[0];
  tx_buf[1] = p[1];
  tx_buf[2] = p[2];
  tx_buf[3] = p[3];
  //帧尾
  tx_buf[4] = 0x00;
  tx_buf[5] = 0x00;
  tx_buf[6] = 0x80;
  tx_buf[7] = 0x7f;
  //函数与外界交互，把数据发出去
  HAL_UART_Transmit(&huart1,tx_buf,8,100);

}

